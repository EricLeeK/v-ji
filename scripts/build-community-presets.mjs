import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { resolve, dirname } from "node:path";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const slugs = ["party-activist", "hubei-selected-graduates"];
const presets = slugs.map((slug) => JSON.parse(readFileSync(resolve(root, "content/presets", `${slug}.json`), "utf8")));
for (const [index, preset] of presets.entries()) {
const { book, notes } = preset;
const payload = JSON.stringify([{ book, notes }]);
if (payload.includes("$exam_presets$")) throw new Error("SQL dollar-quote delimiter appears in content");

const sql = `-- Generated by node scripts/build-community-presets.mjs; edit content/presets/*.json.
-- Idempotent: update only these catalog entries, preserve learner counts and personal copies.
do $seed$
declare
  preset jsonb;
  book_data jsonb;
begin
  for preset in select value from jsonb_array_elements($exam_presets$${payload}$exam_presets$::jsonb)
  loop
    book_data := preset->'book';
    insert into public.books (id, title, description, category, author, is_free, toc)
    values ((book_data->>'id')::uuid, book_data->>'title', book_data->>'description',
            book_data->>'category', book_data->>'author', true, book_data->'toc')
    on conflict (id) do update set
      title = excluded.title, description = excluded.description,
      category = excluded.category, author = excluded.author,
      is_free = excluded.is_free, toc = excluded.toc;

    insert into public.book_notes (id, book_id, chapter, type, fields, importance, sort_order, source, layout, tags)
    select (n->>'id')::uuid, (book_data->>'id')::uuid, n->>'chapter',
           (n->>'type')::public.note_type, n->'fields', n->>'importance',
           (n->>'sort_order')::integer, n->'source', n->>'layout',
           array(select jsonb_array_elements_text(n->'tags'))
    from jsonb_array_elements(preset->'notes') as notes(n)
    on conflict (id) do update set
      chapter = excluded.chapter, type = excluded.type, fields = excluded.fields,
      importance = excluded.importance, sort_order = excluded.sort_order,
      source = excluded.source, layout = excluded.layout, tags = excluded.tags;
  end loop;
end;
$seed$;
`;

const target = resolve(root, `supabase/migrations/20260925220${index + 1}00_${slugs[index]}.sql`);
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== sql) throw new Error("Preset migration is out of date; run node scripts/build-community-presets.mjs");
  console.log("Preset migration matches content.");
} else {
  writeFileSync(target, sql);
  console.log(`Built ${presets.length} books and ${presets.reduce((sum, preset) => sum + preset.notes.length, 0)} notes.`);
}

}
